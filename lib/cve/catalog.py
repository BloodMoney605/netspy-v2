def _build_cpe(product: str, version: str) -> str | None:
    """Arma el nombre CPE 2.3 del producto. None si no hay mapeo."""
    key = re.sub(r"[^a-z0-9.]+", " ", product.lower()).strip()
    entry = CPE_PRODUCTS.get(key)
    if not entry:
        return None
    vendor, cpe_product = entry
    version = version.strip()
    if not version or not re.match(r"^\d+(\.\d+)*", version):
        return None
    return f"cpe:2.3:a:{vendor}:{cpe_product}:{version}:*:*:*:*:*:*:*"


