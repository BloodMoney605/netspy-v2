#!/usr/bin/env python3
"""Fase 5: reporte.

Cada seccion vive en informe/. Ahi se arma el texto y, si la config pide
json, se escribe el volcado estructurado.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from typing import Any

from config import cargar as load_config
from informe.cabecera import seccion as sec_cabecera
from informe.puertos import seccion as sec_puertos
from informe.recon import seccion as sec_recon
from informe.tech import seccion as sec_tech
from informe.vulns import seccion as sec_vulns

SEP = "=" * 70


def load_json(path: str) -> dict:
    if not os.path.exists(path):
        return {}
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def generate_report(input_dir: str, output_dir: str, config: dict | None = None) -> str:
    recon = load_json(os.path.join(input_dir, "recon.json"))
    scan = load_json(os.path.join(input_dir, "ports.json"))
    tech = load_json(os.path.join(input_dir, "tech.json"))
    findings_data = load_json(os.path.join(input_dir, "findings.json"))

    domain = recon.get("domain", os.path.basename(input_dir.rstrip("/\\")))
    findings = findings_data.get("findings", [])
    summary = findings_data.get("summary") or {
        "critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0,
    }
    resumen = dict(summary)
    resumen["total"] = resumen.get("total") or resumen.pop("total_findings", len(findings))

    lineas = sec_cabecera(SEP, domain, time.strftime("%Y-%m-%d %H:%M:%S"), resumen)

    if recon and recon.get("subdomains"):
        lineas += sec_recon(recon, SEP)
    if scan and scan.get("services"):
        lineas += sec_puertos(scan, SEP)
    if tech and (tech.get("alive_hosts") or tech.get("technologies")):
        lineas += sec_tech(tech, SEP)
    if findings:
        lineas += sec_vulns(findings, SEP)

    lineas.append("")
    lineas.append(SEP)
    lineas.append("  Generated by NetSpy")
    lineas.append(SEP)

    formato = (config or {}).get("report", {}).get("format", "txt").lower()

    if formato == "json":
        destino = os.path.join(output_dir, "report.json")
        with open(destino, "w", encoding="utf-8") as f:
            json.dump(
                {
                    "target": domain,
                    "summary": resumen,
                    "recon": recon,
                    "ports": scan,
                    "tech": tech,
                    "findings": findings,
                },
                f,
                indent=2,
                ensure_ascii=False,
                default=str,
            )
    else:
        destino = os.path.join(output_dir, "report.txt")
        with open(destino, "w", encoding="utf-8") as f:
            f.write("\n".join(lineas) + "\n")

    print(f"  reporte: {destino}")
    return destino


def main() -> None:
    parser = argparse.ArgumentParser(description="Fase 5: reporte")
    parser.add_argument("--input", required=True)
    parser.add_argument("--config", default="config/default.yaml")
    parser.add_argument("--output", required=True)
    parser.add_argument("--threads", type=int, default=None)
    args = parser.parse_args()

    config = load_config(args.config)
    os.makedirs(args.output, exist_ok=True)

    try:
        generate_report(args.input, args.output, config)
    except KeyboardInterrupt:
        print("\n  [!] interrumpido")
        sys.exit(130)


if __name__ == "__main__":
    main()